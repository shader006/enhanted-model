#!/usr/bin/env python3
"""Benchmark BraTS preprocessed data loading formats.

This checks the current SegMamba-style contract:
  - .npz exists for case discovery and archive fallback
  - .npy + _seg.npy are the arrays actually read by MedicalDataset
  - .pkl stores properties/metadata

Examples:
  python enhanted-model/mock_test/benchmark_data_loading.py
  python enhanted-model/mock_test/benchmark_data_loading.py --data-dir Segmamba2/SegMamba/data/fullres/train --n-cases 20
"""

