def time_one(fn: Callable[[Path], object], path: Path) -> float:
    gc.collect()
    start = time.perf_counter()
    obj = fn(path)
    elapsed = time.perf_counter() - start
    # Keep a real reference until timing is captured, then release it explicitly.
    del obj
    return elapsed


def benchmark(label: str, fn: Callable[[Path], object], paths: list[Path], repeats: int) -> dict:
    per_case = []
    errors = []

    for path in paths:
        runs = []
        for _ in range(repeats):
            try:
                runs.append(time_one(fn, path))
            except Exception as exc:  # noqa: BLE001 - report benchmark failures, do not hide them
                errors.append(f"{path.name}: {exc}")
                break
        if runs:
            per_case.append(min(runs))

    if not per_case:
        return {"label": label, "n": 0, "errors": errors}

    return {
        "label": label,
        "n": len(per_case),
        "mean_ms": statistics.mean(per_case) * 1000.0,
        "median_ms": statistics.median(per_case) * 1000.0,
        "min_ms": min(per_case) * 1000.0,
        "max_ms": max(per_case) * 1000.0,
        "total_s": sum(per_case),
        "errors": errors,
    }


def case_size_mb(npz_path: Path) -> dict:
    paths = {
        "npz": npz_path,
        "npy": Path(str(npz_path).replace(".npz", ".npy")),
        "seg_npy": Path(str(npz_path).replace(".npz", "_seg.npy")),
        "pkl": Path(str(npz_path).replace(".npz", ".pkl")),
    }
    return {name: path.stat().st_size / 1024 / 1024 for name, path in paths.items() if path.exists()}


def validate_cases(paths: list[Path]) -> list[Path]:
    valid = []
    for path in paths:
        required = [
            Path(str(path).replace(".npz", ".npy")),
            Path(str(path).replace(".npz", "_seg.npy")),
            Path(str(path).replace(".npz", ".pkl")),
        ]
        if all(p.exists() for p in required):
            valid.append(path)
    return valid


def make_uncompressed_npz(paths: list[Path]) -> None:
    for path in paths:
        out_path = path.with_suffix(".uncompressed.npz")
        if out_path.exists():
            continue
        image = np.asarray(np.load(str(path).replace(".npz", ".npy"), mmap_mode="r"))
        seg = np.asarray(np.load(str(path).replace(".npz", "_seg.npy"), mmap_mode="r"))
        np.savez(out_path, data=image, seg=seg)


def cleanup_uncompressed_npz(paths: list[Path]) -> None:
    for path in paths:
        out_path = path.with_suffix(".uncompressed.npz")
        if out_path.exists():
            out_path.unlink()


def make_hdf5(paths: list[Path], gzip: bool = False) -> None:
    if h5py is None:
        raise ModuleNotFoundError("h5py is required for HDF5 benchmark.")

    for path in paths:
        suffix = ".benchmark.gzip.h5" if gzip else ".benchmark.h5"
        out_path = path.with_suffix(suffix)
        if out_path.exists():
            continue

        image = np.asarray(np.load(str(path).replace(".npz", ".npy"), mmap_mode="r"))
        seg = np.asarray(np.load(str(path).replace(".npz", "_seg.npy"), mmap_mode="r"))
        with h5py.File(out_path, "w") as f:
            if gzip:
                f.create_dataset("data", data=image, compression="gzip", compression_opts=1)
                f.create_dataset("seg", data=seg, compression="gzip", compression_opts=1)
            else:
                f.create_dataset("data", data=image)
                f.create_dataset("seg", data=seg)


def cleanup_hdf5(paths: list[Path]) -> None:
    for path in paths:
        for suffix in (".benchmark.h5", ".benchmark.gzip.h5"):
            out_path = path.with_suffix(suffix)
            if out_path.exists():
                out_path.unlink()


def print_table(results: list[dict]) -> None:
    valid = [result for result in results if result.get("n")]
    if not valid:
        print("No successful benchmark result.")
        return

    fastest = min(result["mean_ms"] for result in valid)
    print()
    print(f"{'method':<34} {'n':>4} {'mean':>10} {'median':>10} {'min':>10} {'max':>10} {'x':>6}")
    print("-" * 92)
    for result in sorted(valid, key=lambda item: item["mean_ms"]):
        ratio = result["mean_ms"] / fastest
        print(
            f"{result['label']:<34} {result['n']:>4} "
            f"{result['mean_ms']:>9.1f}ms {result['median_ms']:>9.1f}ms "
            f"{result['min_ms']:>9.1f}ms {result['max_ms']:>9.1f}ms {ratio:>5.2f}x"
        )

    print()
    for result in results:
        if result.get("errors"):
            print(f"[WARN] {result['label']} errors:")
            for error in result["errors"][:5]:
                print(f"  - {error}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-dir",
        default=None,
        help="Folder containing .npz/.npy/_seg.npy/.pkl preprocessed cases.",
    )
    parser.add_argument("--n-cases", type=int, default=10)
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--shuffle", action="store_true")
    parser.add_argument(
        "--include-uncompressed-npz",
        action="store_true",
        help="Create temporary *.uncompressed.npz files and benchmark them too.",
    )
    parser.add_argument(
        "--include-hdf5",
        action="store_true",
        help="Create temporary uncompressed HDF5 files and benchmark them too.",
    )
    parser.add_argument(
        "--include-hdf5-gzip",
        action="store_true",
        help="Create temporary gzip-compressed HDF5 files and benchmark them too.",
    )
    parser.add_argument(
        "--include-np-load-modes",
        action="store_true",
        help="Compare np.load(...), mmap_mode='r', and mmap_mode='r+' directly.",
    )
    parser.add_argument(
        "--include-sample-dict",
        action="store_true",
        help="Benchmark a mock MedicalDataset.__getitem__ that returns {'data', 'seg', 'properties'}.",
    )
    parser.add_argument(
        "--include-cached-memmap",
        action="store_true",
        help="Compare current per-sample np.load mmap open with cached memmap handles.",
    )
    parser.add_argument(
        "--include-batch-crop",
        action="store_true",
        help="Benchmark mock DataLoaderMultiProcess crop-and-pad batch generation.",
    )
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--patch-size", type=int, nargs=3, default=[96, 96, 96])
    parser.add_argument(
        "--keep-temp",
        action="store_true",
        help="Keep temporary *.uncompressed.npz files when --include-uncompressed-npz is used.",
    )
    parser.add_argument("--json-out", default=None, help="Optional path to write raw benchmark results.")
    args = parser.parse_args()

    candidates = [
        args.data_dir,
        "enhanted-model/data/fullres/train",
        "enhanted-model/advanced_model/data/fullres/train",
        "SegMamba/data/fullres/train",
        "Segmamba2/SegMamba/data/fullres/train",
    ]
    data_dir = next((Path(p) for p in candidates if p and Path(p).is_dir()), None)
    if data_dir is None:
        raise FileNotFoundError("Could not find a preprocessed data folder. Pass --data-dir explicitly.")

    paths = [Path(p) for p in sorted(glob.glob(str(data_dir / "*.npz"))) if ".uncompressed." not in p]
    paths = validate_cases(paths)
    if args.shuffle:
        random.Random(args.seed).shuffle(paths)
    paths = paths[: args.n_cases]

    if not paths:
        raise FileNotFoundError(f"No valid cases found in {data_dir}")

    print(f"data_dir: {data_dir}")
    print(f"cases: {len(paths)} / repeats: {args.repeats}")
    print(f"sample case: {paths[0].name}")
    print(f"sample sizes MB: {case_size_mb(paths[0])}")
    print(f"numpy temp dir: {tempfile.gettempdir()}")

    results = []
    try:
        if args.include_uncompressed_npz:
            make_uncompressed_npz(paths)
        if args.include_hdf5:
            make_hdf5(paths, gzip=False)
        if args.include_hdf5_gzip:
            make_hdf5(paths, gzip=True)

        if args.include_np_load_modes:
            tests: list[tuple[str, Callable[[Path], object]]] = [
                ("np.load(...) RAM + .pkl", load_npy_default_ram),
                ("np.load(..., mmap_mode='r') + .pkl", load_npy_mmap_readonly),
                ("np.load(..., mmap_mode='r+') + .pkl", load_npy_mmap_readwrite),
            ]
        elif args.include_sample_dict:
            tests = [
                (
                    "sample dict mmap='r' cached pkl",
                    benchmark_sample_dict_dataset(paths, mmap_mode="r", materialize=False),
                ),
                (
                    "sample dict mmap='r+' cached pkl",
                    benchmark_sample_dict_dataset(paths, mmap_mode="r+", materialize=False),
                ),
                (
                    "sample dict np.load RAM cached pkl",
                    benchmark_sample_dict_dataset(paths, mmap_mode=None, materialize=False),
                ),
                (
                    "sample dict mmap='r' materialized",
                    benchmark_sample_dict_dataset(paths, mmap_mode="r", materialize=True),
                ),
            ]
        elif args.include_cached_memmap:
            tests = [
                (
                    "sample dict open memmap each call",
                    benchmark_sample_dict_dataset(paths, mmap_mode="r", materialize=False),
                ),
                (
                    "sample dict cached memmap handles",
                    benchmark_cached_sample_dict_dataset(paths, mmap_mode="r", materialize=False),
                ),
                (
                    "sample dict cached handles materialized",
                    benchmark_cached_sample_dict_dataset(paths, mmap_mode="r", materialize=True),
                ),
            ]
        elif args.include_batch_crop:
            patch_size = tuple(args.patch_size)
            tests = [
                (
                    f"batch crop open memmap B={args.batch_size}",
                    benchmark_batch_crop_dataset(
                        paths,
                        cached_handles=False,
                        batch_size=args.batch_size,
                        patch_size=patch_size,
                        seed=args.seed,
                    ),
                ),
                (
                    f"batch crop cached memmap B={args.batch_size}",
                    benchmark_batch_crop_dataset(
                        paths,
                        cached_handles=True,
                        batch_size=args.batch_size,
                        patch_size=patch_size,
                        seed=args.seed,
                    ),
                ),
            ]
        else:
            tests = [
                ("current .npy mmap + .pkl", load_current_mmap),
                ("current .npy materialized + .pkl", load_current_materialized),
                (".npy materialized only", load_npy_no_pkl),
                ("compressed .npz + .pkl", load_npz_compressed),
            ]
        if args.include_uncompressed_npz:
            tests.append(("uncompressed .npz + .pkl", load_npz_uncompressed))
        if args.include_hdf5:
            tests.append(("HDF5 uncompressed + .pkl", load_hdf5_uncompressed))
        if args.include_hdf5_gzip:
            tests.append(("HDF5 gzip-1 + .pkl", load_hdf5_gzip))

        for label, fn in tests:
            print(f"running: {label}")
            results.append(benchmark(label, fn, paths, args.repeats))
    finally:
        if args.include_uncompressed_npz and not args.keep_temp:
            cleanup_uncompressed_npz(paths)
        if (args.include_hdf5 or args.include_hdf5_gzip) and not args.keep_temp:
            cleanup_hdf5(paths)

    print_table(results)

    if args.json_out:
        out_path = Path(args.json_out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump({"data_dir": str(data_dir), "cases": [p.name for p in paths], "results": results}, f, indent=2)
        print(f"wrote: {out_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
