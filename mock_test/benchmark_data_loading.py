def load_current_mmap(npz_path: Path):
    """Current dataset behavior: open .npy memmaps and read .pkl metadata."""
    image = np.load(str(npz_path).replace(".npz", ".npy"), mmap_mode="r")
    seg = np.load(str(npz_path).replace(".npz", "_seg.npy"), mmap_mode="r")
    with open(str(npz_path).replace(".npz", ".pkl"), "rb") as f:
        props = pickle.load(f)
    return image, seg, props


def load_npy_default_ram(npz_path: Path):
    """Load .npy arrays into RAM with np.load(...) and read .pkl metadata."""
    image = np.load(str(npz_path).replace(".npz", ".npy"))
    seg = np.load(str(npz_path).replace(".npz", "_seg.npy"))
    with open(str(npz_path).replace(".npz", ".pkl"), "rb") as f:
        props = pickle.load(f)
    return image, seg, props


def load_npy_mmap_readonly(npz_path: Path):
    """Open .npy arrays with np.load(..., mmap_mode='r') and read .pkl metadata."""
    image = np.load(str(npz_path).replace(".npz", ".npy"), mmap_mode="r")
